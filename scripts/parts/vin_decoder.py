# ---------------------------------------------------------------------------
# 4. Decode
# ---------------------------------------------------------------------------
def decode(raw: str, today: int = None) -> dict:
    today = today or date.today().year
    vin = normalize_vin(raw)
    out = {"vin": vin, "valid": False, "errors": [], "maker": None, "years": [], "year_confidence": None,
           "model_hints": [], "mercedes_series": None, "check_digit_ok": None, "maker_source": None}

    if len(vin) != 17:
        out["errors"].append(f"Le VIN doit contenir 17 caractères (ici {len(vin)}).")
        return out
    if not VIN_CHARS.match(vin):
        out["errors"].append("Caractères non valides : seulement lettres (sauf I, O, Q) et chiffres.")
        return out
    out["valid"] = True
    out["check_digit_ok"] = check_digit_ok(vin)

    maker, out["maker_source"] = maker_from_wmi(vin)
    out["maker"] = maker
    if not maker:
        out["errors"].append("Constructeur non reconnu : choisissez la marque manuellement.")
        return out

    if maker in YEAR_RELIABLE or maker in YEAR_MAYBE:
        out["years"] = model_years(vin[9], today)
        out["year_confidence"] = "high" if maker in YEAR_RELIABLE else "medium"

    if maker in VAG:
        out["model_hints"] = VAG_CODES.get(vin[6:8], [])
    elif maker == "MERCEDES-BENZ" and vin[3:6].isdigit():
        out["mercedes_series"] = vin[3:6]                 # "204" -> W204 / S204 / X204
    return out

# ---------------------------------------------------------------------------
# 5. Match against catalogue models  (models = list of dicts from the DB)
#    keys: id, maker, name, generation, year_from, year_to
# ---------------------------------------------------------------------------
def _year_fits(m, years):
    if not years or m["year_from"] is None:
        return True
    end = m["year_to"] or 9999
    # model year can be 1 year ahead of production start
    return any(m["year_from"] - 1 <= y <= end + 1 for y in years)

MB_SUV_WMI = {"WDC", "W1N", "4JG"}                         # Mercedes SUVs
MB_SUV_NAMES = ("GL", "ML", "Classe G")

def match_models(decoded: dict, models: list) -> dict:
    """Returns {"level": exact|model|make|none, "candidates": [...], "year": best guess or None}."""
    maker = decoded.get("maker")
    if maker == "MINI":                                    # Mini models are stored under BMW
        pool = [m for m in models if m["maker"] == "BMW" and m["name"].startswith("Mini")]
    else:
        pool = [m for m in models if m["maker"] == maker and not m["name"].startswith("Mini")]
    if not pool:
        return {"level": "none", "candidates": [], "year": None}
    res = _match(decoded, pool)
    res["year"] = next((y for y in decoded["years"]
                        if any(_year_fits(m, [y]) for m in res["candidates"])), None)
    if res["year"]:                                        # keep the most recent cycle only (2014, not 1984)
        res["candidates"] = [m for m in res["candidates"] if _year_fits(m, [res["year"]])]
        if res["level"] == "model" and len(res["candidates"]) == 1:
            res["level"] = "exact"
    return res

def _match(decoded, pool):
    hits = []
    if decoded["model_hints"]:
        for name, gen in decoded["model_hints"]:
            hits += [m for m in pool if m["name"] == name and (not gen or (m["generation"] or "") == gen)]
    elif decoded["mercedes_series"]:
        s = decoded["mercedes_series"]
        hits = [m for m in pool if re.search(rf"\b[A-Z]{{1,2}}{s}\b", m["generation"] or "")]
        suv = decoded["vin"][:3] in MB_SUV_WMI
        pref = [m for m in hits if m["name"].startswith(MB_SUV_NAMES) == suv]
        hits = pref or hits

    if hits:
        by_year = [m for m in hits if _year_fits(m, decoded["years"])] or hits
        return {"level": "exact" if len(by_year) == 1 else "model", "candidates": by_year}

    by_year = [m for m in pool if _year_fits(m, decoded["years"])]
    return {"level": "make", "candidates": sorted(by_year or pool, key=lambda m: (m["name"], m["generation"] or ""))}

