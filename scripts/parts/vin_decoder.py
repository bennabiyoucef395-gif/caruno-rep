# ---------------------------------------------------------------------------
# 1. Cleaning & validation
# ---------------------------------------------------------------------------
VIN_CHARS = re.compile(r"^[A-HJ-NPR-Z0-9]{17}$")          # no I, O, Q in a VIN

def normalize_vin(raw: str) -> str:
    v = re.sub(r"[\s\-\.]", "", (raw or "").upper())
    return v.replace("I", "1").replace("O", "0").replace("Q", "0")

TRANSLIT = {**{str(d): d for d in range(10)},
            **dict(zip("ABCDEFGH", range(1, 9))), **dict(zip("JKLMN", range(1, 6))),
            "P": 7, "R": 9, **dict(zip("STUVWXYZ", range(2, 10)))}
WEIGHTS = [8, 7, 6, 5, 4, 3, 2, 10, 0, 9, 8, 7, 6, 5, 4, 3, 2]

def check_digit_ok(vin: str) -> bool:
    """Char 9 check digit. Mandatory in North America only: informative here."""
    total = sum(TRANSLIT[c] * w for c, w in zip(vin, WEIGHTS))
    expected = "X" if total % 11 == 10 else str(total % 11)
    return vin[8] == expected

