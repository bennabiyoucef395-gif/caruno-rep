def _load_nhtsa():
    """WMI_NHTSA from wmi_nhtsa.py next to this file (generated by scripts/vehicle-ref/build.sh nhtsa).
    Loaded by path: python -I does not put the script's folder on sys.path."""
    import importlib.util, os
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "wmi_nhtsa.py")
    if not os.path.exists(path):
        return {}
    spec = importlib.util.spec_from_file_location("wmi_nhtsa", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.WMI_NHTSA

WMI_NHTSA = _load_nhtsa()

def maker_from_wmi(vin: str):
    """(maker, source). The hand-written WMI table always wins; then NHTSA (6-char key first for small
    makers, whose WMI ends in 9 and continues in chars 12-14); then the 2-char prefixes."""
    if vin[:3] in WMI:
        return WMI[vin[:3]], "hand"
    if vin[2] == "9" and vin[:3] + vin[11:14] in WMI_NHTSA:
        return WMI_NHTSA[vin[:3] + vin[11:14]], "nhtsa"
    if vin[:3] in WMI_NHTSA:
        return WMI_NHTSA[vin[:3]], "nhtsa"
    if vin[:2] in WMI_PREFIX2:
        return WMI_PREFIX2[vin[:2]], "hand"
    return None, None

# Makers whose char 10 is a reliable model year (European-market VINs)
YEAR_RELIABLE = {"VW", "AUDI", "SEAT", "SKODA", "PORSCHE", "BMW", "MINI", "HYUNDAI", "KIA"}
YEAR_MAYBE = {"TOYOTA", "LEXUS", "LAND ROVER"}            # often right, ask the customer to confirm
# Mercedes, Renault, PSA... (non-US VINs) do not encode the year in char 10

YEAR_CODES = "ABCDEFGHJKLMNPRSTVWXY123456789"          # A=1980/2010 ... 9=2009 (30-year cycle)

def model_years(code: str, today: int):
    if code not in YEAR_CODES:
        return []
    base = 1980 + YEAR_CODES.index(code)
    return [y for y in (base + 30, base) if 1980 <= y <= today + 1]   # most recent first

