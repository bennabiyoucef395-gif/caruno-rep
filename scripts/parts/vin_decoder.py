# MariaDB helper (database caruno_parts, PyMySQL or mysql-connector connection)
# ---------------------------------------------------------------------------
SQL_MODELS = """
SELECT m.id, mf.name AS maker, m.name, m.generation, m.year_from, m.year_to
FROM models m JOIN manufacturers mf ON mf.id = m.manufacturer_id
WHERE mf.name = %s
"""

def connect_mariadb(host="localhost", port=3306, user="caruno_parts", password="", database="caruno_parts"):
    """Read-only connection to caruno_parts. utf8mb4 without forcing a collation: the server default
    (utf8mb4_uca1400_ai_ci, the database's) is kept, so text comparisons stay accent-insensitive."""
    import pymysql
    return pymysql.connect(host=host, port=int(port), user=user, password=password, database=database, charset="utf8mb4")

def decode_and_match(conn, raw_vin: str) -> dict:
    d = decode(raw_vin)
    if not d["maker"]:
        return {"decoded": d, "match": {"level": "none", "candidates": []}}
    maker = "BMW" if d["maker"] == "MINI" else d["maker"]      # Mini models are stored under BMW
    with conn.cursor() as cur:
        cur.execute(SQL_MODELS, (maker,))
        cols = [c[0] for c in cur.description]
        models = [dict(zip(cols, r)) for r in cur.fetchall()]
    for m in models:                                           # MariaDB SMALLINT/INT come back as int already
        for k in ("year_from", "year_to"):
            m[k] = int(m[k]) if m[k] is not None else None
    return {"decoded": d, "match": match_models(d, models)}

