"""
CARUNO — export the VIN decoder rules of vin_decoder.py (+ wmi_nhtsa.py) to JSON for the Dolibarr add-on
(dolibarr-modules/caruno/data/vin_rules.json, read by class/caruno_vin.class.php). vin_decoder.py stays the only
source: re-run after any change (provisioning/40-caruno-module.sh runs it before installing).
Also writes vin_cases.json: the Python answers for the test VINs, so the PHP port is checked against them
(provisioning/tests/vehicles-api.mjs).

Usage: python -I vin_rules.py <out_dir> [models.csv manufacturers.csv]
"""
import csv, importlib.util, json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("vin_decoder", os.path.join(here, "vin_decoder.py"))
vd = importlib.util.module_from_spec(spec); spec.loader.exec_module(vd)

TEST_VINS = [
    "WVWZZZAUZFW123456",   # Golf 7
    "WAUZZZ8K9BA123456",   # A4 B8
    "WDD2040081A123456",   # Mercedes W204
    "TMBJJ7NE5F0123456",   # Skoda Octavia 3
    "WBA3A5C50CF123456",   # BMW (make level)
    "VF1RJL00067123456",   # Renault Arkana: maker known, no catalogue model
    "UU1KSDAFH47123456",   # Dacia: maker known, no catalogue model
    "1G1ZD5ST0JF123456",   # NHTSA code
    "LB2ABCDE1F1234567",   # unknown maker
    "wvw zzz au-zfw 123456",  # typed with spaces / lower case
    "WVWZZZAUZFW12345",    # 16 characters
]

def main(out, models_csv=None, makers_csv=None):
    rules = {
        "source": "scripts/parts/vin_decoder.py + wmi_nhtsa.py (generated by scripts/parts/vin_rules.py, do not edit)",
        "wmi": vd.WMI, "wmi_nhtsa": vd.WMI_NHTSA, "wmi_prefix2": vd.WMI_PREFIX2,
        "year_reliable": sorted(vd.YEAR_RELIABLE), "year_maybe": sorted(vd.YEAR_MAYBE), "year_codes": vd.YEAR_CODES,
        "translit": vd.TRANSLIT, "weights": vd.WEIGHTS,
        "vag": sorted(vd.VAG), "vag_codes": {k: [list(x) for x in v] for k, v in vd.VAG_CODES.items()},
        "mb_suv_wmi": sorted(vd.MB_SUV_WMI), "mb_suv_names": list(vd.MB_SUV_NAMES),
    }
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "vin_rules.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(rules, f, ensure_ascii=False, indent=1, sort_keys=True)
    print(f"  vin_rules.json: {len(vd.WMI)} hand-written WMI, {len(vd.WMI_NHTSA)} NHTSA, {len(vd.VAG_CODES)} VW-group codes")
    if models_csv:
        makers = {r["id"]: r["name"] for r in csv.DictReader(open(makers_csv, encoding="utf-8"))}
        models = [{"id": int(r["id"]), "maker": makers[r["manufacturer_id"]], "name": r["name"],
                   "generation": r["generation"] or None,
                   "year_from": int(r["year_from"]) if r["year_from"] else None,
                   "year_to": int(r["year_to"]) if r["year_to"] else None}
                  for r in csv.DictReader(open(models_csv, encoding="utf-8"))]
        cases = []
        for vin in TEST_VINS:
            d = vd.decode(vin, today=2026)
            maker = "BMW" if d["maker"] == "MINI" else d["maker"]
            m = vd.match_models(d, [x for x in models if x["maker"] == maker]) if d["maker"] else {"level": "none", "candidates": [], "year": None}
            cases.append({"input": vin, "vin": d["vin"], "valid": d["valid"], "maker": d["maker"], "years": d["years"],
                          "level": m["level"], "year": m.get("year"),
                          "candidates": sorted(f'{c["maker"]}|{c["name"]}|{c["generation"] or ""}' for c in m["candidates"])})
        with open(os.path.join(out, "vin_cases.json"), "w", encoding="utf-8", newline="\n") as f:
            json.dump(cases, f, ensure_ascii=False, indent=1)
        print(f"  vin_cases.json: {len(cases)} test VINs (Python answers, year 2026)")

if __name__ == "__main__":
    if len(sys.argv) not in (2, 4):
        sys.exit(__doc__)
    main(*sys.argv[1:])
