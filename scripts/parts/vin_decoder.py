"""
CARUNO — VIN decoder (free, rule-based).

What it does:
  1. Cleans what the customer typed (spaces, lowercase, I->1, O/Q->0) and checks 17 chars.
  2. Finds the maker from the WMI (chars 1-3): hand-written table first, then NHTSA (wmi_nhtsa.py).
  3. Reads the model year (char 10) when that maker really encodes it.
  4. Reads the model code when the maker puts one in the VIN:
       - VW group: chars 7-8  (WVWZZZ AU Z ... -> Golf 7)
       - Mercedes: chars 4-6  (WDD 204 ... -> W204 / S204 / X204)
  5. Proposes the matching catalogue models (filtered by production years),
     so the customer only has to confirm model, date and engine.

The decoder never "invents" a model: when it is not sure it returns several
candidates (or the whole make) and the customer chooses.

Usage (CLI test):  python vin_decoder.py WVWZZZAUZFW123456 out/models.csv out/manufacturers.csv
(out = C:/Users/TRETEC/caruno-data/parts-build, files from scripts/parts/build.sh data)
"""
import csv, re, sys
